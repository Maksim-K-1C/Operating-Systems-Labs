#!/bin/sh
touch my_test
whoami > my_test     #имя текущего пользователя
id >> my_test        #идентификаторы UID and GID
groups >> my_test    #список всех групп пользователя
who >> my_test       #список активных пользователей в системе
last -n 5 >> my_test #история последних 5 входов в систему
uname -a >>my_test   #подробная информация об ОС и ядре
lsb_release -a >> my_test #точная версия дистрибутива
uptime >> my_test    #время работы компьютера без перезагрузки
free -h >> my_test   #информация об оперативной памяти 
df -h >> my_test     #заполненность дисков файловой системы
